      el.dataset.joditInit = '1';
      Jodit.make(el, fbJoditOptions());
    });
  }
  // Bootstrap fires shown.bs.tab when a tab becomes visible; initialize any editors deferred above.
  document.addEventListener('shown.bs.tab', initJoditEditors);
