/**
 * Builds the British English (en_gb) language files from the US English (en_us) ones.
 *
 *   php docs/tools/build_en_gb.php            show what would be written, change nothing
 *   php docs/tools/build_en_gb.php --write    write the en_gb files
 *   php docs/tools/build_en_gb.php --check    exit 1 if any en_gb file is missing or out of date
 *   php docs/tools/build_en_gb.php --diff     list every phrase that changes, US => UK
 *
 * Run it with --write after changing any en_us language file. An en_gb file is a full copy of its
 * en_us file with the rules in en_gb_rules.php applied; a file the rules leave unchanged gets no
 * en_gb copy, and FreeBooks then uses the en_us file for it. A language file that exists must hold
 * every phrase (FreeBooks falls back to en_us per file, not per phrase), which is why the copies are
 * generated rather than edited: an en_gb file can never lack a phrase its en_us file has.
 *
 * Generated files say so in their header; one whose en_us file no longer needs a copy is deleted.
 * Covers trunk/ and extensions/, but not Zen Cart's own files (ZenCartFiles) or vendor code.
 */
$repo  = realpath(__DIR__ . '/../..');
$rules = require __DIR__ . '/en_gb_rules.php';
$mode  = in_array('--write', $argv, true) ? 'write' : (in_array('--check', $argv, true) ? 'check' : (in_array('--diff', $argv, true) ? 'diff' : 'show'));
const GENERATED_MARK = 'Generated by docs/tools/build_en_gb.php from the en_us file. Change the rules there, not this file.';

// ── Parsing ─────────────────────────────────────────────────────────────────────

// Every define('NAME', value) in a PHP source, with the byte range of its value.
function gb_defines(string $src): array {
  $toks = token_get_all($src); $n = count($toks); $offs = []; $pos = 0;
  foreach ($toks as $t) { $offs[] = $pos; $pos += strlen(is_array($t) ? $t[1] : $t); }
  $offs[] = $pos;
  $sig = function ($i) use ($toks, $n) { while ($i < $n && is_array($toks[$i]) && in_array($toks[$i][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT])) $i++; return $i; };
  $out = [];
  for ($i = 0; $i < $n; $i++) {
    if (!is_array($toks[$i]) || $toks[$i][0] !== T_STRING || strtolower($toks[$i][1]) !== 'define') continue;
    $j = $sig($i + 1); if ($j >= $n || $toks[$j] !== '(') continue;
    $k = $sig($j + 1); if (!is_array($toks[$k]) || $toks[$k][0] !== T_CONSTANT_ENCAPSED_STRING) continue;
    $c = $sig($k + 1); if ($toks[$c] !== ',') continue;
    $depth = 1; $m = $c + 1;
    for (; $m < $n; $m++) { if ($toks[$m] === '(') $depth++; elseif ($toks[$m] === ')' && --$depth === 0) break; }
    $start = $offs[$sig($c + 1)]; $end = $offs[$m];
    while ($end > $start && ctype_space($src[$end - 1])) $end--;
    $out[] = ['name' => trim($toks[$k][1], "'\""), 'start' => $start, 'end' => $end, 'expr' => substr($src, $start, $end - $start)];
  }
  return $out;
}

// ── The rules ───────────────────────────────────────────────────────────────────

// The replacement for $word, in the case of $word (word, Word, Two Words or WORD).
function gb_case(string $word, string $repl): string {
  if ($word === strtoupper($word) && strtolower($word) !== $word) return strtoupper($repl);
  if (strpos($word, ' ') !== false && $word === ucwords(strtolower($word))) return ucwords($repl);
  if ($word[0] === strtoupper($word[0]) && ctype_alpha($word[0])) return ucfirst($repl);
  return $repl;
}

// Applies the spelling rules to plain text (no tags), leaving protected spans untouched.
function gb_spell(string $text, array $rules): string {
  $hold = [];
  foreach ($rules['protect'] as $rx) {
    $text = preg_replace_callback($rx, function ($m) use (&$hold) { $hold[] = $m[0]; return "\x01" . (count($hold) - 1) . "\x02"; }, $text);
  }
  foreach ($rules['spelling'] as $pattern => $to) {
    $text = preg_replace_callback('/\b' . $pattern . '\b/i', function ($m) use ($to) {
      $lower = strtolower($m[0]);
      if (is_array($to)) return isset($to[$lower]) ? gb_case($m[0], $to[$lower]) : $m[0];
      return gb_case($m[0], preg_replace_callback('/\$(\d)/', fn($g) => strtolower($m[(int)$g[1]] ?? ''), $to));
    }, $text);
  }
  return preg_replace_callback("/\x01(\d+)\x02/", fn($m) => $hold[(int)$m[1]], $text);
}

// Applies the spelling rules to the visible text of a PHP value expression: the inside of each
// string literal, outside HTML tags.
function gb_expr(string $expr, array $rules): string {
  $toks = token_get_all('<?php ' . $expr); array_shift($toks); $out = '';
  foreach ($toks as $t) {
    if (is_array($t) && $t[0] === T_CONSTANT_ENCAPSED_STRING) {
      $q = $t[1][0]; $inner = substr($t[1], 1, -1);
      $parts = preg_split('/(<[^>]*>)/', $inner, -1, PREG_SPLIT_DELIM_CAPTURE);
      foreach ($parts as $i => $p) if ($i % 2 === 0) $parts[$i] = gb_spell($p, $rules);
      $out .= $q . implode('', $parts) . $q;
    } else {
      $out .= is_array($t) ? $t[1] : $t;
    }
  }
  return $out;
}

// ── Files ───────────────────────────────────────────────────────────────────────

function gb_en_us_files(string $repo): array {
  $files = [];
  foreach (['trunk', 'extensions'] as $top) {
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator("$repo/$top", FilesystemIterator::SKIP_DOTS));
    foreach ($it as $f) {
      $p = $f->getPathname();
      if (substr($p, -4) !== '.php' || strpos($p, '/en_us/') === false) continue;
      if (preg_match('#/(manual|vendor)/|ZenCartFiles#', $p)) continue;
      $files[] = $p;
    }
  }
  sort($files);
  return $files;
}

// Where a repository file sits in an installation, for the header's Path line: trunk/ is the web
// root, and an extension is copied into modules/ (a shipping method into modules/shipping/methods/).
function gb_installed_path(string $rel): string {
  $map = ['#^trunk/#' => '/', '#^extensions/Modules/zencart/PhreeBooksFiles/#' => '/',
          '#^extensions/Modules/#' => '/modules/', '#^extensions/ShippingMethods/#' => '/modules/shipping/methods/',
          '#^extensions/PaymentMethods/#' => '/modules/payment/methods/'];
  foreach ($map as $rx => $to) if (preg_match($rx, $rel)) return preg_replace($rx, $to, $rel);
  return '/' . $rel;
}

// The en_us file's source with its header (the copyright box, the Path line and a bare //
// after it) replaced by the generated file's own.
function gb_with_header(string $src, string $path_comment): string {
  $lines = explode("\n", $src); $i = 1;
  while ($i < count($lines) && preg_match('#^//(\s*[+|].*|\s*Path:.*|\s*)$#', $lines[$i])) $i++;
  $head = [
    '<?php',
    '// +-----------------------------------------------------------------+',
    '// |                          FreeBooks ERP                          |',
    '// +-----------------------------------------------------------------+',
    '// | Copyright(c) 2026 Bill Jones                                    |',
    '// +-----------------------------------------------------------------+',
    '// | This program is free software: you can redistribute it and/or   |',
    '// | modify it under the terms of the GNU General Public License as  |',
    '// | published by the Free Software Foundation, either version 3 of  |',
    '// | the License, or any later version.                              |',
    '// |                                                                 |',
    '// | This program is distributed in the hope that it will be useful, |',
    '// | but WITHOUT ANY WARRANTY; without even the implied warranty of  |',
    '// | MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the   |',
    '// | GNU General Public License for more details.                    |',
    '// +-----------------------------------------------------------------+',
    '//  Path: ' . $path_comment,
    '//  ' . GENERATED_MARK,
    '//',
  ];
  return implode("\n", array_merge($head, array_slice($lines, $i)));
}

// ── Build ───────────────────────────────────────────────────────────────────────

$phrase_rules = $rules['phrases']; $used = [];
$want = []; $changes = [];
foreach (gb_en_us_files($repo) as $en) {
  $src = file_get_contents($en); $defs = gb_defines($src); $changed = 0;
  foreach (array_reverse($defs) as $d) {
    $new = isset($rules['locale'][$d['name']]) && strpos($en, '/modules/phreedom/language/') !== false
      ? $rules['locale'][$d['name']] : gb_expr($d['expr'], $rules);
    foreach ($phrase_rules[$d['name']] ?? [] as $us => $uk) {
      if (strpos($new, $us) === false) { fwrite(STDERR, "The US text \"$us\" is no longer in $d[name] (" . substr($en, strlen($repo) + 1) . "). Update en_gb_rules.php.\n"); exit(1); }
      $new = str_replace($us, $uk, $new); $used[$d['name']] = true;
    }
    if ($new === $d['expr']) continue;
    if (strpos($new, "\x01") !== false) { fwrite(STDERR, "Protected text not restored in $d[name]\n"); exit(1); }
    $changes[] = [substr($en, strlen($repo) + 1), $d['name'], $d['expr'], $new];
    $src = substr($src, 0, $d['start']) . $new . substr($src, $d['end']); $changed++;
  }
  if (!$changed) continue;
  $src = strtr($src, $rules['file_text']);
  $gb = str_replace('/en_us/', '/en_gb/', $en);
  $want[$gb] = gb_with_header($src, gb_installed_path(substr($gb, strlen($repo) + 1)));
}
foreach ($phrase_rules as $name => $_) {
  if (empty($used[$name])) { fwrite(STDERR, "No en_us phrase named $name - update en_gb_rules.php.\n"); exit(1); }
}

// Generated en_gb files that are no longer wanted.
$stale = [];
foreach (gb_en_us_files($repo) as $en) {
  $gb = str_replace('/en_us/', '/en_gb/', $en);
  if (!isset($want[$gb]) && is_file($gb) && strpos(file_get_contents($gb), GENERATED_MARK) !== false) $stale[] = $gb;
}

$out_of_date = [];
foreach ($want as $gb => $content) if (!is_file($gb) || file_get_contents($gb) !== $content) $out_of_date[] = $gb;

if ($mode === 'diff') {
  foreach ($changes as [$file, $name, $us, $uk]) printf("%s  %s\n  US %s\n  UK %s\n", $file, $name, $us, $uk);
}
printf("%d phrases change, in %d files; %d en_gb files to write, %d to delete.\n", count($changes), count($want), count($out_of_date), count($stale));
if ($mode === 'check') exit($out_of_date || $stale ? 1 : 0);
if ($mode === 'write') {
  foreach ($out_of_date as $gb) { if (!is_dir(dirname($gb))) mkdir(dirname($gb), 0775, true); file_put_contents($gb, $want[$gb]); }
  foreach ($stale as $gb) unlink($gb);
  echo "Written.\n";
}
